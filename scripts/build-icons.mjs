// Builds the Tabler icon data used by Muna.
//   npm pack @tabler/icons && tar xzf tabler-icons-*.tgz -C /some/new/dir
//   node scripts/build-icons.mjs /some/new/dir/package
// Output: icons/index.json (names + search tags) and icons/{o,f}/<first-letter>.json (svg markup).
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-icons.mjs <path to @tabler/icons package>'); process.exit(1); }
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'icons');
rmSync(out, { recursive: true, force: true });

const meta = JSON.parse(readFileSync(join(src, 'icons.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(src, 'package.json'), 'utf8')).version;

const shardOf = (name) => (/^[a-z]/.test(name) ? name[0] : '_');
const inner = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z"\s*(fill="none")?\s*\/>/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>')
    .trim();

const shards = { o: {}, f: {} };
const flags = {};
for (const [key, style] of [['o', 'outline'], ['f', 'filled']]) {
  for (const file of readdirSync(join(src, 'icons', style))) {
    const name = file.replace(/\.svg$/, '');
    const markup = inner(readFileSync(join(src, 'icons', style, file), 'utf8'));
    (shards[key][shardOf(name)] ??= {})[name] = markup;
    flags[name] = (flags[name] || 0) | (key === 'o' ? 1 : 2);
  }
}

const names = Object.keys(flags).sort();
const index = {
  version,
  // [name, searchable text, flags (1 = outline, 2 = filled)]
  icons: names.map((n) => {
    const m = meta[n] || {};
    const words = [...new Set([...(m.tags || []), m.category || ''].map(String))].join(' ').toLowerCase();
    return [n, words, flags[n]];
  }),
};
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'index.json'), JSON.stringify(index));
for (const key of ['o', 'f']) {
  mkdirSync(join(out, key), { recursive: true });
  for (const [s, data] of Object.entries(shards[key])) writeFileSync(join(out, key, `${s}.json`), JSON.stringify(data));
}

// Icons used by the app chrome itself are inlined so they render instantly.
const UI = ['home-2','article','messages','user-circle','layout-dashboard','pennant','plus','minus','check','chevron-left','chevron-right',
  'x','search','pencil','edit','flame','bolt','trash','copy','camera','users','user-plus','user-minus','user-check','heart','message-circle','send',
  'lock','world','dots','arrow-back-up','player-play','player-pause','bell','logout','refresh','shield-check','crown','circle-check',
  'alert-circle','clock','calendar','photo','sparkles','arrow-left','door-exit','star','eye','filter','chart-bar','settings','share-3','user-x','photo-off'];
const ui = {};
for (const n of UI) {
  const o = shards.o[shardOf(n)]?.[n], f = shards.f[shardOf(n)]?.[n];
  if (!o) throw new Error('missing UI icon ' + n);
  ui[n] = f ? { o, f } : { o };
}
writeFileSync(join(out, '..', 'js', 'ui-icons.js'),
  '// Generated by scripts/build-icons.mjs (Tabler Icons, MIT).\nexport const UI = ' + JSON.stringify(ui) + ';\n');
console.log(`tabler ${version}: ${names.length} icons`,
  `(${Object.keys(shards.o).length ? Object.values(shards.o).reduce((a, s) => a + Object.keys(s).length, 0) : 0} outline,`,
  `${Object.values(shards.f).reduce((a, s) => a + Object.keys(s).length, 0)} filled)`);
